const KEY = "pa_lang";
let lang = "zh";
try {
  const saved = localStorage.getItem(KEY);
  if (saved === "zh" || saved === "en") lang = saved;
} catch {}

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  try { localStorage.setItem(KEY, l); } catch {}
  document.documentElement.lang = l === "zh" ? "zh-HK" : "en";
}

// Pick the current language from a { zh, en } object (or return a plain string).
export const L = (o) => (o && typeof o === "object" ? o[lang] ?? o.en : o ?? "");

// Look up UI copy and fill {placeholders}.
export function t(key, vars = {}) {
  const s = L(UI[key]) || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Fill every element marked data-i18n="key" with its text.
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
}
